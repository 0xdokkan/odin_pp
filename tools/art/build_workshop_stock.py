"""Bake immutable workshop paintings from the authoritative Odin routines.

No drawing formulas are duplicated here. --check verifies version, source and
artifact hashes without compiling; --verify rebuilds and compares every byte.
The temporary Odin program uses CPU images only and never opens a GL context.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "assets/workshop-stock"
GENERATED = ROOT / "src/render/expedition_workshop_stock_data.odin"
VERSION = 1
NAMES = {
    "src/render/expedition_workshop_stock.odin": ("WORKSHOP_STOCK_SIDE", "workshop_ground_smooth", "workshop_ground_pixels"),
    "src/render/expedition_cyber_floor.odin": ("CYBER_FLOOR_ROUTES", "CYBER_FLOOR_BENDS", "cyber_workshop_ground_sample"),
    "src/render/expedition_west_ground.odin": ("WEST_GROUND_BASE", "WEST_GROUND_ROUTES", "WEST_GROUND_BENDS", "west_ground_smooth", "west_ground_mix", "west_workshop_ground_sample"),
}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def declaration(text, name):
    match = re.search(r"^" + re.escape(name) + r"\s*::", text, re.M)
    if not match:
        raise RuntimeError("Missing authoritative declaration: " + name)
    start = match.start()
    line_end = text.index("\n", start)
    opening = text.find("{", start, line_end)
    if opening < 0:
        return text[start:line_end] + "\n"
    depth = 0
    for index in range(opening, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start:index + 1] + "\n"
    raise RuntimeError("Unclosed declaration: " + name)


def sources():
    chunks = []
    for path, names in NAMES.items():
        text = (ROOT / path).read_text()
        chunks.extend(declaration(text, name) for name in names)
    return "\n".join(chunks)


def fingerprint(pure):
    return sha((str(VERSION) + "\n" + pure).encode())


def data_file(source_hash):
    return f'''// Generated by tools/art/build_workshop_stock.py; do not edit.
package render

WORKSHOP_STOCK_ASSET_VERSION :: {VERSION}
WORKSHOP_STOCK_SOURCE_SHA256 :: "{source_hash}"
WORKSHOP_STOCK_CYBER_PNG :: #load("../../assets/workshop-stock/cyber.png")
WORKSHOP_STOCK_WEST_PNG :: #load("../../assets/workshop-stock/west.png")
'''.encode()


def check(pure):
    metadata = DEST / "manifest.json"
    if not metadata.exists():
        return False
    info = json.loads(metadata.read_text())
    if info.get("version") != VERSION or info.get("source_sha256") != fingerprint(pure):
        return False
    if info.get("generator_sha256") != sha(Path(__file__).read_bytes()):
        return False
    if not GENERATED.exists() or GENERATED.read_bytes() != data_file(fingerprint(pure)):
        return False
    return all((DEST / name).exists() and sha((DEST / name).read_bytes()) == digest
               for name, digest in info["png_sha256"].items())


def build(pure, target):
    program = '''package main
import "core:fmt"
import "core:math"
import "core:os"
import "core:strings"
import rl "vendor:raylib"
Stock_Biome :: enum {Cyber, West}
''' + pure.replace("campaign.Biome", "Stock_Biome") + '''
main :: proc() {
    assert(len(os.args)==2)
    rl.SetTraceLogLevel(.WARNING)
    for biome,i in ([2]Stock_Biome{.Cyber,.West}) {
        pixels:=workshop_ground_pixels(biome)
        name:="cyber" if i==0 else "west"
        path:=fmt.aprintf("%s/%s.png",os.args[1],name)
        filename:=strings.clone_to_cstring(path)
        image:=rl.Image{data=raw_data(pixels),width=WORKSHOP_STOCK_SIDE,height=WORKSHOP_STOCK_SIDE,mipmaps=1,format=.UNCOMPRESSED_R8G8B8A8}
        assert(rl.ExportImage(image,filename))
        decoded:=rl.LoadImage(filename)
        assert(decoded.width==image.width && decoded.height==image.height)
        rl.ImageFormat(&decoded,.UNCOMPRESSED_R8G8B8A8)
        colors:=(cast([^]rl.Color)decoded.data)[:len(pixels)]
        for pixel,j in pixels {assert(pixel==colors[j],"PNG altered the generated pigment")}
        raw_path:=fmt.aprintf("%s/%s.rgba",os.args[1],name)
        bytes:=(cast([^]u8)raw_data(pixels))[:len(pixels)*size_of(rl.Color)]
        assert(os.write_entire_file(raw_path,bytes)==nil)
        rl.UnloadImage(decoded);delete(raw_path);delete(filename);delete(path);delete(pixels)
    }
}
'''
    (ROOT / "build").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="workshop-stock-", dir=ROOT / "build") as temp:
        temp = Path(temp)
        (temp / "main.odin").write_text(program)
        binary = temp / "generator"
        subprocess.run([os.environ.get("ODIN", "odin"), "build", str(temp), "-o:speed", "-out:" + str(binary)], check=True)
        subprocess.run([str(binary), str(target)], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    pure = sources()
    if args.check:
        if not check(pure):
            raise SystemExit("Workshop stock is stale or missing; run python3 tools/art/build_workshop_stock.py")
        print("Workshop stock source/artifact hashes verified")
        return
    with tempfile.TemporaryDirectory(prefix="workshop-pixels-") as temp:
        output = Path(temp)
        build(pure, output)
        metadata = {"version": VERSION, "source_sha256": fingerprint(pure),
                    "generator_sha256": sha(Path(__file__).read_bytes()), "width": 1024, "height": 1024,
                    "format": "RGBA8 sRGB pigment", "png_sha256": {}, "pixels_sha256": {}}
        for name in ("cyber", "west"):
            metadata["png_sha256"][name + ".png"] = sha((output / (name + ".png")).read_bytes())
            metadata["pixels_sha256"][name] = sha((output / (name + ".rgba")).read_bytes())
        if args.verify:
            assert check(pure), "Stored source/artifact hashes differ"
            existing = json.loads((DEST / "manifest.json").read_text())
            assert existing == metadata, "Regenerated paintings differ"
            print("Both 1024x1024 paintings reproduced; PNG roundtrip preserves every RGBA pixel")
        else:
            DEST.mkdir(parents=True, exist_ok=True)
            for name in ("cyber.png", "west.png"):
                shutil.copyfile(output / name, DEST / name)
            (DEST / "manifest.json").write_text(json.dumps(metadata, indent=2) + "\n")
            GENERATED.write_bytes(data_file(fingerprint(pure)))
            print("Wrote workshop paintings, manifest and embedded-data declarations")


if __name__ == "__main__":
    main()
